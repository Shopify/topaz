#!/usr/bin/env python3
"""Generate topaz/prism/nodes.py from vendor/prism/config.yml.

Run with Python 3 from the repository root:

    python3 topaz/prism/gen.py

config.yml is read with `ruby` (to avoid depending on PyYAML); set $RUBY to
pick a specific one.  The output is RPython (and so Python 2).
"""

import json
import os
import re
import subprocess
import sys


HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, os.pardir, os.pardir))
CONFIG = os.path.join(ROOT, "vendor", "prism", "config.yml")
OUTPUT = os.path.join(HERE, "nodes.py")
VERSION_H = os.path.join(ROOT, "vendor", "prism", "include", "prism", "version.h")


def load_config():
    ruby = os.environ.get("RUBY", "ruby")
    out = subprocess.check_output([
        ruby, "-ryaml", "-rjson", "-e",
        "puts JSON.dump(YAML.load_file(ARGV[0]))", CONFIG,
    ])
    return json.loads(out)


def load_version():
    with open(VERSION_H) as f:
        text = f.read()
    return tuple(
        int(re.search(r"#define PRISM_VERSION_%s (\d+)" % part, text).group(1))
        for part in ["MAJOR", "MINOR", "PATCH"]
    )


def snake(name):
    return re.sub(r"(?<!^)(?=[A-Z])", "_", name).lower()


def constant_name(name):
    return re.sub(r"(?<!^)(?=[A-Z])", "_", name).upper()


# How each field type is stored on the node, and how it is read.
LOADERS = {
    "node": "self.load_node()",
    "node?": "self.load_optional_node()",
    "node[]": "self.load_node_list()",
    "string": "self.load_string()",
    "constant": "self.load_constant()",
    "constant?": "self.load_optional_constant()",
    "constant[]": "self.load_constant_list()",
    "location": "self.load_location()",
    "location?": "self.load_optional_location()",
    "uint8": "self.load_byte()",
    "uint32": "self.load_varuint()",
    "integer": "self.load_integer()",
    "double": "self.load_double()",
}

RESERVED = {"from", "and", "or", "not", "in", "is", "if", "else", "return",
            "def", "class", "lambda", "global", "pass", "yield", "print",
            "exec", "while", "for", "try", "with", "as", "assert", "del",
            "import", "raise", "break", "continue", "elif", "except",
            "finally"}


def attr_name(field):
    name = field["name"]
    if name in RESERVED:
        name += "_"
    return name


HEADER = '''\
# This file is generated by topaz/prism/gen.py from vendor/prism/config.yml.
# Do not edit it by hand.
"""Prism's syntax tree, and a loader for its serialization format.

See vendor/prism/serialization.md for the format.  Locations are byte
offsets into the source; Loader.line_of() turns them into line numbers.
"""

from rpython.rlib.rarithmetic import intmask
from rpython.rlib.rbigint import rbigint
from rpython.rlib.rstruct.runpack import runpack


MAJOR_VERSION = %(major)d
MINOR_VERSION = %(minor)d
PATCH_VERSION = %(patch)d

# Flags shared by all nodes.
NODE_FLAG_NEWLINE = 1
NODE_FLAG_STATIC_LITERAL = 2
'''

BODY = '''

class Location(object):
    _immutable_fields_ = ["start", "length"]

    def __init__(self, start, length):
        self.start = start
        self.length = length

    def end(self):
        return self.start + self.length


class Node(object):
    _attrs_ = ["node_id", "location", "flags"]

    TYPE = 0
    NAME = "Node"

    def __init__(self, node_id, location, flags):
        self.node_id = node_id
        self.location = location
        self.flags = flags

    def start(self):
        return self.location.start

    def has_flag(self, flag):
        return (self.flags & flag) != 0

    def accept(self, visitor):
        raise NotImplementedError


class Diagnostic(object):
    def __init__(self, type, message, location, level):
        self.type = type
        self.message = message
        self.location = location
        self.level = level


class LoadError(Exception):
    def __init__(self, msg):
        self.msg = msg
'''

LOADER = '''

class Loader(object):
    def __init__(self, source, serialized):
        self.source = source
        self.data = serialized
        self.pos = 0
        self.start_line = 1
        self.newline_offsets = []
        self.errors = []
        self.warnings = []
        self.cpool_base = 0
        self.cpool_size = 0

    def load(self):
        self.load_header()
        return self.load_node()

    def load_header(self):
        if self.data[0:5] != "PRISM":
            raise LoadError("invalid serialization")
        self.pos = 5
        if (self.load_byte() != MAJOR_VERSION or
                self.load_byte() != MINOR_VERSION or
                self.load_byte() != PATCH_VERSION):
            raise LoadError("serialized with a different version of Prism")
        if self.load_byte() != 0:
            raise LoadError("location fields are missing")
        self.load_embedded_string()  # encoding name
        self.start_line = self.load_varsint()
        count = self.load_varuint()
        offsets = [0] * count
        for i in range(count):
            offsets[i] = self.load_varuint()
        self.newline_offsets = offsets
        for i in range(self.load_varuint()):  # comments
            self.load_varuint()
            self.load_location()
        for i in range(self.load_varuint()):  # magic comments
            self.load_location()
            self.load_location()
        self.load_optional_location()  # __END__
        self.errors = self.load_diagnostics()
        self.warnings = self.load_diagnostics()
        self.cpool_base = self.load_uint32()
        self.cpool_size = self.load_varuint()

    def load_diagnostics(self):
        count = self.load_varuint()
        result = [None] * count
        for i in range(count):
            type = self.load_varuint()
            message = self.load_embedded_string()
            location = self.load_location()
            level = self.load_byte()
            result[i] = Diagnostic(type, message, location, level)
        return result

    def line_of(self, offset):
        """The line number the given byte offset is on."""
        offsets = self.newline_offsets
        lo = 0
        hi = len(offsets)
        while lo < hi:
            mid = (lo + hi) >> 1
            if offsets[mid] <= offset:
                lo = mid + 1
            else:
                hi = mid
        return self.start_line + lo - 1

    def load_byte(self):
        b = ord(self.data[self.pos])
        self.pos += 1
        return b

    def load_varuint(self):
        n = self.load_byte()
        if n < 128:
            return n
        n -= 128
        shift = 0
        while True:
            b = self.load_byte()
            shift += 7
            if b < 128:
                return n + (b << shift)
            n += (b - 128) << shift

    def load_varsint(self):
        n = self.load_varuint()
        return (n >> 1) ^ (-(n & 1))

    def load_uint32(self):
        pos = self.pos
        self.pos = pos + 4
        return (ord(self.data[pos]) | (ord(self.data[pos + 1]) << 8) |
                (ord(self.data[pos + 2]) << 16) |
                (ord(self.data[pos + 3]) << 24))

    def _uint32_at(self, pos):
        return (ord(self.data[pos]) | (ord(self.data[pos + 1]) << 8) |
                (ord(self.data[pos + 2]) << 16) |
                (ord(self.data[pos + 3]) << 24))

    def load_double(self):
        pos = self.pos
        assert pos >= 0
        self.pos = pos + 8
        return runpack("d", self.data[pos:pos + 8])

    def load_integer(self):
        negative = self.load_byte() != 0
        length = self.load_varuint()
        value = rbigint.fromint(0)
        for i in range(length):
            word = rbigint.fromint(self.load_varuint())
            value = value.or_(word.lshift(32 * i))
        if negative:
            value = value.neg()
        return value

    def load_embedded_string(self):
        length = self.load_varuint()
        pos = self.pos
        end = pos + length
        assert pos >= 0
        assert end >= 0
        self.pos = end
        return self.data[pos:end]

    def load_string(self):
        type = self.load_byte()
        if type == 1:
            start = self.load_varuint()
            end = start + self.load_varuint()
            assert start >= 0
            assert end >= 0
            return self.source[start:end]
        elif type == 2:
            return self.load_embedded_string()
        raise LoadError("unknown string type")

    def load_location(self):
        start = self.load_varuint()
        return Location(start, self.load_varuint())

    def load_optional_location(self):
        if self.data[self.pos] == "\\x00":
            self.pos += 1
            return None
        self.pos += 1
        return self.load_location()

    def constant(self, index):
        entry = self.cpool_base + (index - 1) * 8
        start = self._uint32_at(entry)
        length = self._uint32_at(entry + 4)
        if start & (1 << 31):
            start &= ~(1 << 31)
            end = start + length
            assert start >= 0
            assert end >= 0
            return self.data[start:end]
        end = start + length
        assert start >= 0
        assert end >= 0
        return self.source[start:end]

    def load_constant(self):
        return self.constant(self.load_varuint())

    def load_optional_constant(self):
        index = self.load_varuint()
        if index == 0:
            return None
        return self.constant(index)

    def load_constant_list(self):
        count = self.load_varuint()
        result = [""] * count
        for i in range(count):
            result[i] = self.load_constant()
        return result

    def load_optional_node(self):
        if self.data[self.pos] == "\\x00":
            self.pos += 1
            return None
        return self.load_node()

    def load_node_list(self):
        count = self.load_varuint()
        result = [None] * count
        for i in range(count):
            result[i] = self.load_node()
        return result

    def load_node(self):
        type = self.load_byte()
        node_id = self.load_varuint()
        location = self.load_location()
        if type == %(lazy)d:
            # Method definitions are prefixed with their serialized length,
            # so that loaders can skip over their bodies.
            self.pos += 4
        flags = self.load_varuint()
'''


def generate(config, version):
    out = [HEADER % {"major": version[0], "minor": version[1],
                     "patch": version[2]}]

    for flags in config["flags"]:
        out.append("\n# %s\n" % flags["comment"].strip().rstrip("."))
        prefix = constant_name(flags["name"])
        if prefix.endswith("_FLAGS"):
            pass
        for i, value in enumerate(flags["values"]):
            out.append("%s_%s = %d\n" % (prefix, value["name"], 1 << (i + 2)))

    out.append(BODY)

    nodes = config["nodes"]
    for type_id, node in enumerate(nodes, 1):
        fields = node.get("fields", [])
        params = ", ".join(attr_name(f) for f in fields)
        out.append("\n\nclass %s(Node):\n" % node["name"])
        attrs = ", ".join('"%s"' % attr_name(f) for f in fields)
        out.append("    _attrs_ = [%s]\n\n" % attrs)
        out.append("    TYPE = %d\n" % type_id)
        out.append('    NAME = "%s"\n\n' % node["name"])
        if fields:
            out.append("    def __init__(self, node_id, location, flags, %s):\n" % params)
        else:
            out.append("    def __init__(self, node_id, location, flags):\n")
        out.append("        Node.__init__(self, node_id, location, flags)\n")
        for f in fields:
            out.append("        self.%s = %s\n" % (attr_name(f), attr_name(f)))
        out.append("\n    def accept(self, visitor):\n")
        out.append("        return visitor.visit_%s(self)\n" % snake(node["name"]))

    out.append("\n\nclass Visitor(object):\n")
    out.append('    """Dispatch target for Node.accept(); every visit method falls\n')
    out.append('    back to visit_default()."""\n\n')
    out.append("    def visit_default(self, node):\n")
    out.append("        raise NotImplementedError(node.NAME)\n")
    for node in nodes:
        out.append("\n    def visit_%s(self, node):\n" % snake(node["name"]))
        out.append("        return self.visit_default(node)\n")

    lazy = [i for i, node in enumerate(nodes, 1) if node["name"] == "DefNode"]
    assert len(lazy) == 1
    out.append(LOADER % {"lazy": lazy[0]})
    for type_id, node in enumerate(nodes, 1):
        fields = node.get("fields", [])
        keyword = "if" if type_id == 1 else "elif"
        out.append("        %s type == %d:\n" % (keyword, type_id))
        if fields:
            out.append("            return %s(\n" % node["name"])
            out.append("                node_id, location, flags,\n")
            for f in fields:
                out.append("                %s,\n" % LOADERS[f["type"]])
            out.append("            )\n")
        else:
            out.append("            return %s(node_id, location, flags)\n" % node["name"])
    out.append('        raise LoadError("unknown node type %d" % type)\n')
    return "".join(out)


def main():
    source = generate(load_config(), load_version())
    with open(OUTPUT, "w") as f:
        f.write(source)
    print("wrote %s" % os.path.relpath(OUTPUT, ROOT))


if __name__ == "__main__":
    sys.exit(main())
